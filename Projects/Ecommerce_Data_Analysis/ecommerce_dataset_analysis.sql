-- Customer Lifetime Value tiering: For each customer, calculate total revenue generated (only from 'Completed' orders), then label them 'Gold' (>10000), 'Silver' (3000–10000), or 'Bronze' (<3000) using a CTE + CASE.
WITH customer_revenue AS (
    SELECT c.customer_id,
           SUM(p.price * oi.quantity) AS total_revenue
    FROM orders o
    JOIN order_items oi ON o.order_id = oi.order_id
    JOIN products p ON oi.product_id = p.product_id
    JOIN customers c ON o.customer_id = c.customer_id
    WHERE o.status = 'Completed'
    GROUP BY c.customer_id
)
SELECT c.customer_name, cr.total_revenue,
	CASE
		WHEN cr.total_revenue > 1500000 THEN 'Gold'
        WHEN cr.total_revenue < 1500000 AND cr.total_revenue > 1000000 THEN 'Silver'
        ELSE 'Bronze'
	END AS Tier
FROM customers c JOIN customer_revenue cr ON c.customer_id = cr.customer_id
ORDER BY cr.total_revenue DESC; 

-- Month-over-month revenue growth: Calculate total revenue per month, then use LAG() to compute the % growth from the previous month.
WITH monthly_rev AS (
    SELECT 
        DATE_FORMAT(o.order_date, '%Y-%m-01') AS month,
        SUM(p.price * oi.quantity) AS revenue
    FROM orders o
    JOIN order_items oi ON o.order_id = oi.order_id
    JOIN products p ON oi.product_id = p.product_id
    WHERE o.status = 'Completed'
    GROUP BY DATE_FORMAT(o.order_date, '%Y-%m-01')
)
SELECT 
    month, 
    revenue,
    LAG(revenue) OVER (ORDER BY month) AS prev_month_revenue,
    ROUND(
        (revenue - LAG(revenue) OVER (ORDER BY month)) * 100.0 
        / LAG(revenue) OVER (ORDER BY month), 2
    ) AS mom_growth_percent
FROM monthly_rev
ORDER BY month;

